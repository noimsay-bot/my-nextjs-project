import fs from "node:fs";
import path from "node:path";
import { codeFiles, listFiles, repoRoot } from "./utils.mjs";

const generatedFiles = [
  ["docs/generated/route-map.md", "scripts/harness/generate-route-map.mjs", () => listFiles("app")],
  [
    "docs/generated/env-map.md",
    "scripts/harness/generate-env-map.mjs",
    () => [path.join(repoRoot, ".env.example"), ...codeFiles()].filter((file) => fs.existsSync(file)),
  ],
  ["docs/generated/supabase-map.md", "scripts/harness/generate-supabase-map.mjs", () => listFiles("supabase", { extensions: [".sql"] })],
  ["docs/generated/package-scripts.md", "scripts/harness/generate-package-scripts.mjs", () => [path.join(repoRoot, "package.json")]],
  [
    "docs/generated/dependency-map.md",
    "scripts/harness/quality-score.mjs",
    () => [
      path.join(repoRoot, "scripts/harness/quality-score.mjs"),
      path.join(repoRoot, "docs/generated/route-map.md"),
      path.join(repoRoot, "docs/generated/env-map.md"),
      path.join(repoRoot, "docs/generated/supabase-map.md"),
      path.join(repoRoot, "docs/generated/package-scripts.md"),
    ],
  ],
  [
    "docs/QUALITY_SCORE.md",
    "scripts/harness/quality-score.mjs",
    () => [
      path.join(repoRoot, "scripts/harness/quality-score.mjs"),
      path.join(repoRoot, "docs/generated/dependency-map.md"),
    ],
  ],
];

const failures = [];

function newestMtime(files) {
  return files
    .filter((file) => fs.existsSync(file))
    .reduce((newest, file) => Math.max(newest, fs.statSync(file).mtimeMs), 0);
}

for (const [docRelative, scriptRelative, inputFiles] of generatedFiles) {
  const docPath = path.join(repoRoot, docRelative);
  const scriptPath = path.join(repoRoot, scriptRelative);
  if (!fs.existsSync(docPath)) {
    failures.push(`${docRelative} missing. Run npm run harness:generate and npm run harness:quality.`);
    continue;
  }
  const text = fs.readFileSync(docPath, "utf8");
  if (!text.includes(`Generated by \`${scriptRelative}\``)) {
    failures.push(`${docRelative} missing generated header for ${scriptRelative}.`);
  }
  const docMtime = fs.statSync(docPath).mtimeMs;
  if (fs.existsSync(scriptPath) && docMtime + 1000 < fs.statSync(scriptPath).mtimeMs) {
    failures.push(`${docRelative} is older than ${scriptRelative}. Regenerate it.`);
  }
  const newestInput = newestMtime(inputFiles());
  if (newestInput && docMtime + 1000 < newestInput) {
    failures.push(`${docRelative} is older than one or more source inputs. Regenerate it.`);
  }
}

if (failures.length) {
  console.error("Generated documentation freshness check failed:");
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

console.log(`generated-freshness: ${generatedFiles.length} generated files checked`);
